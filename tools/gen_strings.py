"""Writes src/Tartarus.App/Localization/Strings.Designer.cs from Strings.resx: what Visual Studio's PublicResXFileCodeGenerator
does, for a build from the command line. Run it after adding or removing a line in Strings.resx."""
import re
from pathlib import Path
from xml.etree import ElementTree

HERE = Path(__file__).resolve().parent.parent / "src" / "Tartarus.App" / "Localization"

names = sorted(d.get("name") for d in ElementTree.parse(HERE / "Strings.resx").getroot().findall("data"))
bad = [n for n in names if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n)]
if bad:
    raise SystemExit(f"not identifiers: {bad}")
lines = [
    "// <auto-generated>By tools/gen_strings.py from Strings.resx.</auto-generated>",
    "#nullable enable",
    "using System.Globalization;",
    "using System.Resources;",
    "",
    "namespace Tartarus.App.Localization;",
    "",
    "/// <summary>The interface's lines by key, in the language of the UI thread's culture (<see cref=\"Loc.Init\"/>).</summary>",
    "public static class Strings",
    "{",
    "    public static ResourceManager ResourceManager { get; } = new(\"Tartarus.App.Localization.Strings\", typeof(Strings).Assembly);",
    "",
    "    private static string Get(string key) => ResourceManager.GetString(key, CultureInfo.CurrentUICulture) ?? key;",
    "",
]
lines += [f"    public static string {n} => Get(nameof({n}));" for n in names]
lines.append("}")
(HERE / "Strings.Designer.cs").write_text("\r\n".join(lines) + "\r\n", encoding="utf-8")
print(len(names), "keys")
